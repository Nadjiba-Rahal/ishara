EPOCHS, MAX_LR, MIN_LR, WD, WARMUP, PATIENCE = 150, 1e-3, 1e-5, 1e-4, 8, 25
DOMAIN_LOSS_WEIGHT = 0.2   # keep the adversarial signal secondary to the main task
BEST_PATH = '/content/ishara_FINAL_best.pt'
criterion = nn.CrossEntropyLoss(label_smoothing=0.05)
domain_criterion = nn.CrossEntropyLoss()
optimizer = torch.optim.AdamW(model.parameters(), lr=MAX_LR, weight_decay=WD)
scaler = torch.amp.GradScaler('cuda', enabled=USE_AMP)

def get_lr(epoch):
    if epoch <= WARMUP:
        return MIN_LR + (MAX_LR - MIN_LR) * (epoch / WARMUP)
    prog = (epoch - WARMUP) / (EPOCHS - WARMUP)
    return MIN_LR + (MAX_LR - MIN_LR) * 0.5 * (1 + math.cos(math.pi * prog))

def get_alpha(epoch):
    # standard DANN ramp: 0 -> 1 over training, so early epochs focus on
    # learning the task at all before asking for signer-invariance too.
    p = epoch / EPOCHS
    return (2.0 / (1.0 + math.exp(-10 * p)) - 1.0)

ema_model = copy.deepcopy(model)
for p in ema_model.parameters(): p.requires_grad_(False)
EMA_DECAY = 0.999

@torch.no_grad()
def update_ema():
    for ep, mp_ in zip(ema_model.parameters(), model.parameters()):
        ep.mul_(EMA_DECAY).add_(mp_, alpha=1 - EMA_DECAY)

def train_one_epoch(loader, alpha):
    model.train()
    total = correct = 0; loss_sum = 0.0
    epoch_start = time.time()
    total_batches = len(loader)
    for batch_index, (x, y, signer_id) in enumerate(loader, start=1):
        x = x.to(DEVICE, non_blocking=True)
        y = y.to(DEVICE, non_blocking=True)
        signer_id = signer_id.to(DEVICE, non_blocking=True)
        optimizer.zero_grad(set_to_none=True)
        with torch.amp.autocast(device_type='cuda', enabled=USE_AMP):
            class_logits, domain_logits = model(x, alpha=alpha)
            loss = criterion(class_logits, y) + DOMAIN_LOSS_WEIGHT * domain_criterion(domain_logits, signer_id)
        scaler.scale(loss).backward()
        scaler.unscale_(optimizer)
        torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
        scaler.step(optimizer); scaler.update()
        update_ema()
        loss_sum += loss.item() * len(y)
        correct += (class_logits.argmax(1) == y).sum().item()
        total += len(y)
        if batch_index == 1 or batch_index % 10 == 0 or batch_index == total_batches:
            elapsed = time.time() - epoch_start
            rate = batch_index / max(elapsed, 1e-6)
            remaining = max(total_batches - batch_index, 0) / max(rate, 1e-6)
            print(
                f"  batch {batch_index:03d}/{total_batches} | "
                f"loss={loss.item():.4f} | "
                f"elapsed={elapsed / 60:.1f}m | ETA={remaining / 60:.1f}m",
                flush=True,
            )
    return loss_sum / total, correct / total

@torch.no_grad()
def evaluate(loader, eval_model):
    eval_model.eval()
    total = correct = 0
    for x, y, _ in loader:
        x, y = x.to(DEVICE), y.to(DEVICE)
        class_logits, _ = eval_model(x, alpha=0.0)
        correct += (class_logits.argmax(1) == y).sum().item()
        total += len(y)
    return correct / total if total else 0.0

best_val, best_epoch, no_improve = -1.0, 0, 0
for epoch in range(1, EPOCHS + 1):
    lr = get_lr(epoch)
    for g in optimizer.param_groups: g['lr'] = lr
    alpha = get_alpha(epoch)
    train_loss, train_acc = train_one_epoch(train_loader, alpha)
    val_acc = evaluate(val_loader, model)
    ema_val_acc = evaluate(val_loader, ema_model)
    eval_acc = max(val_acc, ema_val_acc)
    eval_model = ema_model if ema_val_acc >= val_acc else model
    print(f'Epoch {epoch:03d}/{EPOCHS} | train={train_acc:.2%} | val={val_acc:.2%} | EMA={ema_val_acc:.2%} | alpha={alpha:.2f} | lr={lr:.2e}')
    if eval_acc > best_val:
        best_val, best_epoch, no_improve = eval_acc, epoch, 0
        torch.save({'epoch': epoch, 'model_state_dict': eval_model.state_dict(),
                    'best_val_acc': best_val, 'labels': labels}, BEST_PATH)
        print(f'    NEW BEST: {best_val:.2%}')
    else:
        no_improve += 1
    if no_improve >= PATIENCE:
        print(f'Early stopping at epoch {epoch}. Best: {best_val:.2%} (epoch {best_epoch})')
        break

checkpoint = torch.load(BEST_PATH, map_location=DEVICE)
