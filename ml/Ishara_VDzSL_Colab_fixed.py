def frame_features(rgb):
    mp_image = mp.Image(image_format=mp.ImageFormat.SRGB, data=rgb)
    pose_result = pose_landmarker.detect(mp_image)
    hand_result = hand_landmarker.detect(mp_image)

    pose = np.zeros((33, 4), np.float32)
    if pose_result.pose_landmarks:
        for i, lm in enumerate(pose_result.pose_landmarks[0]):
            pose[i] = [lm.x, lm.y, lm.z, getattr(lm, 'visibility', 1.0)]

    left, right = np.zeros((21, 3), np.float32), np.zeros((21, 3), np.float32)
    if hand_result.hand_landmarks:
        for hand_lm, handedness in zip(hand_result.hand_landmarks, hand_result.handedness):
            pts = np.array([[lm.x, lm.y, lm.z] for lm in hand_lm], np.float32)
            if handedness[0].category_name == 'Left':
                left = pts
            else:
                right = pts

    center = (pose[23, :3] + pose[24, :3]) / 2 if np.any(pose[23, :3]) and np.any(pose[24, :3]) else np.array([.5, .5, 0], np.float32)
    scale = max(float(np.linalg.norm(pose[11, :3] - pose[12, :3])), 1e-4)
    for a in (pose, left, right):
        a[:, :3] = (a[:, :3] - center) / scale
    return np.concatenate([pose.ravel(), left.ravel(), right.ravel()]).astype(np.float32)

DEBUG_PRINTED = 0

def extract_video(path):
    global DEBUG_PRINTED
    cap = cv2.VideoCapture(path)
    if not cap.isOpened():
        if DEBUG_PRINTED < 3:
            print('DEBUG: could not open ->', path)
            DEBUG_PRINTED += 1
        cap.release()
        return None

    total = int(cap.get(cv2.CAP_PROP_FRAME_COUNT))
    if total <= 0:
        # CAP_PROP_FRAME_COUNT is unreliable for some containers -- count manually.
        count = 0
        while True:
            ok = cap.grab()
            if not ok:
                break
            count += 1
        total = count
        cap.release()
        cap = cv2.VideoCapture(path)  # reopen to read from the start
        if DEBUG_PRINTED < 3:
            print(f'DEBUG: frame count unreliable, manually counted {total} frames ->', path)
            DEBUG_PRINTED += 1

    if total <= 0:
        if DEBUG_PRINTED < 3:
            print('DEBUG: zero frames even after manual count ->', path)
            DEBUG_PRINTED += 1
        cap.release()
        return None

    idxs = set(np.linspace(0, total - 1, FRAMES).astype(int).tolist())
    out = []
    frame_i = 0
    grabbed = {}
    # sequential read + selective decode -- more robust than POS_FRAMES seeking
    # for containers with unreliable seek tables.
    while len(grabbed) < len(idxs):
        ok = cap.grab()
        if not ok:
            break
        if frame_i in idxs:
            ok2, frame = cap.retrieve()
            if ok2:
                grabbed[frame_i] = frame
        frame_i += 1
    cap.release()

    for idx in sorted(idxs):
        frame = grabbed.get(idx)
        if frame is None:
            out.append(np.zeros(FEATURES, np.float32))
        else:
            out.append(frame_features(cv2.cvtColor(frame, cv2.COLOR_BGR2RGB)))

    arr = np.asarray(out, np.float32)
    return arr if arr.shape == (FRAMES, FEATURES) else None
