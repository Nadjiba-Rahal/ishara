import math, copy

DEVICE = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
USE_AMP = DEVICE.type == 'cuda'
NUM_CLASSES = len(labels)

class GradientReversal(torch.autograd.Function):
    @staticmethod
    def forward(ctx, x, alpha):
        ctx.alpha = alpha
        return x.view_as(x)
    @staticmethod
    def backward(ctx, grad_output):
        return -ctx.alpha * grad_output, None

def grad_reverse(x, alpha):
    return GradientReversal.apply(x, alpha)

class IsharaFinal(nn.Module):
    def __init__(self, n_classes, n_signers, input_size):
        super().__init__()
        self.input_norm = nn.LayerNorm(input_size)
        self.lstm = nn.LSTM(input_size=input_size, hidden_size=192, num_layers=2,
                             batch_first=True, bidirectional=True, dropout=0.30)
        self.attention = nn.Sequential(nn.Linear(384, 128), nn.Tanh(), nn.Linear(128, 1))
        self.classifier = nn.Sequential(
            nn.LayerNorm(768), nn.Linear(768, 384), nn.GELU(), nn.Dropout(0.35),
            nn.Linear(384, 192), nn.GELU(), nn.Dropout(0.25), nn.Linear(192, n_classes))
        # signer-discriminator head -- trained adversarially via grad_reverse
        # so the SHARED features become signer-invariant, not signer-predictive.
        self.domain_head = nn.Sequential(
            nn.Linear(768, 128), nn.ReLU(), nn.Dropout(0.3), nn.Linear(128, n_signers))

    def forward(self, x, alpha=0.0):
        x = self.input_norm(x)
        y, _ = self.lstm(x)
        w = torch.softmax(self.attention(y), dim=1)
        attn_pool = torch.sum(w * y, dim=1)
        max_pool = torch.max(y, dim=1).values
        features = torch.cat([attn_pool, max_pool], dim=1)
        class_logits = self.classifier(features)
        domain_logits = self.domain_head(grad_reverse(features, alpha))
        return class_logits, domain_logits

model = IsharaFinal(NUM_CLASSES, NUM_SIGNERS, MODEL_INPUT_SIZE).to(DEVICE)
