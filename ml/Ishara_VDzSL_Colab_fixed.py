def rotate_xy(a, angle_rad):
    c, s = math.cos(angle_rad), math.sin(angle_rad)
    x, y = a[..., 0].copy(), a[..., 1].copy()
    a[..., 0] = x * c - y * s
    a[..., 1] = x * s + y * c
    return a

class SignDataset(Dataset):
    def __init__(self, rs, augment=False):
        self.rs, self.augment = rs, augment

    def __len__(self):
        return len(self.rs)

    def __getitem__(self, i):
        r = self.rs[i]
        x = np.load(r['cache']).copy()  # (16, 258)
        pose = x[:, :132].reshape(16, 33, 4)
        left = x[:, 132:195].reshape(16, 21, 3)
        right = x[:, 195:258].reshape(16, 21, 3)

        if self.augment:
            # -- mirror (disable if handedness is semantically meaningful) --
            if random.random() < 0.5:
                for a in (pose, left, right):
                    a[..., 0] *= -1
                left, right = right.copy(), left.copy()

            # -- simulated camera tilt --
            if random.random() < 0.5:
                angle = math.radians(random.uniform(-8, 8))
                for a in (pose, left, right):
                    rotate_xy(a[..., :3], angle)

            # -- simulated distance-from-camera jitter --
            if random.random() < 0.5:
                scale = random.uniform(0.9, 1.1)
                for a in (pose, left, right):
                    a[..., :3] *= scale

            # -- simulated off-center framing --
            if random.random() < 0.4:
                off = np.random.uniform(-0.05, 0.05, size=2).astype(np.float32)
                for a in (pose, left, right):
                    a[..., 0] += off[0]
                    a[..., 1] += off[1]

            # -- simulated dropped hand tracking (real MediaPipe failure mode) --
            if random.random() < 0.15:
                left[:] = 0
            if random.random() < 0.15:
                right[:] = 0

            # -- mild temporal jitter: hold a pose one frame longer --
            if random.random() < 0.3:
                idx = random.randint(1, 14)
                pose[idx] = pose[idx - 1]
                left[idx] = left[idx - 1]
                right[idx] = right[idx - 1]

            # -- gaussian sensor noise --
            if random.random() < 0.45:
                for a in (pose, left, right):
                    a[..., :3] += np.random.randn(*a[..., :3].shape).astype(np.float32) * 0.008

        raw = np.concatenate([pose.reshape(16, -1), left.reshape(16, -1), right.reshape(16, -1)], axis=1)
        velocity = np.diff(raw, axis=0, prepend=raw[0:1])
        full = np.concatenate([raw, velocity], axis=1).astype(np.float32)  # (16, 516)

        signer_id = signer_to_id.get(r.get('signer'), 0)
        return (torch.tensor(full, dtype=torch.float32),
                torch.tensor(r['label_id'], dtype=torch.long),
                torch.tensor(signer_id, dtype=torch.long))

